const botName=document.querySelector("#botName");
const skinEnabled=document.querySelector("#skinEnabled");
const skinUrl=document.querySelector("#skinUrl");
const skinModel=document.querySelector("#skinModel");
const output=document.querySelector("#output");
const preview=document.querySelector("#skinPreview");
const apiUrl=document.querySelector("#apiUrl");
const apiToken=document.querySelector("#apiToken");
const connectionStatus=document.querySelector("#connectionStatus");
const saveStatus=document.querySelector("#saveStatus");
const movementMode=document.querySelector("#movementMode");
const jumpChance=document.querySelector("#jumpChance");
const walkInterval=document.querySelector("#walkInterval");

function normalizedApiUrl(){return apiUrl.value.trim().replace(/\/+$/,"")}
function remotePayload(){
  return {
    skin:{
      enabled:skinEnabled.checked,
      username:botName.value.trim(),
      textureUrl:skinUrl.value.trim(),
      model:skinModel.value
    },
    bot:{
      movementMode:movementMode.value,
      jumpChance:Number(jumpChance.value),
      walkIntervalMs:Number(walkInterval.value)
    }
  };
}
function yaml(){
  const config=remotePayload();
  const q=value=>JSON.stringify(value);
  return [
    "# Generated by ABS Control Panel. Keep API tokens out of this file.",
    "api:",
    '  base-url: "https://your-abs-service.example.com"',
    '  token: ""',
    "  poll-seconds: 30",
    "",
    "skin:",
    "  apply-on-join: true",
    "  username: "+q(config.skin.username),
    "  enabled: "+config.skin.enabled,
    "  texture-url: "+q(config.skin.textureUrl),
    "  model: "+q(config.skin.model),
    ""
  ].join("\n");
}
function render(){
  output.textContent=yaml();
  const url=skinUrl.value.trim();
  preview.replaceChildren();
  if(!url){preview.textContent="No skin selected";return}
  if(!/^https:\/\/textures\.minecraft\.net\/texture\/[a-fA-F0-9]+$/.test(url)){
    preview.textContent="Use a textures.minecraft.net texture URL.";
    return;
  }
  const img=document.createElement("img");
  img.src=url;img.alt="Minecraft skin texture preview";
  img.onerror=()=>{preview.textContent="The texture could not be previewed."};
  preview.appendChild(img);
}
function credentialsValid(){
  if(!normalizedApiUrl().startsWith("https://"))throw new Error("API URL must use HTTPS.");
  if(apiToken.value.length<32)throw new Error("Token must be at least 32 characters.");
}
async function apiRequest(method="GET",body){
  credentialsValid();
  const response=await fetch(normalizedApiUrl()+"/api/v1/config",{
    method,
    headers:{"Authorization":"Bearer "+apiToken.value,"Accept":"application/json",...(body?{"Content-Type":"application/json"}:{})},
    ...(body?{body:JSON.stringify(body)}:{})
  });
  const data=await response.json().catch(()=>({error:"ABS API returned an unreadable response."}));
  if(!response.ok)throw new Error(data.error||("ABS API returned HTTP "+response.status));
  return data;
}
function setForm(data){
  botName.value=data.skin.username;
  skinEnabled.checked=data.skin.enabled;
  skinUrl.value=data.skin.textureUrl||"";
  skinModel.value=data.skin.model;
  movementMode.value=data.bot.movementMode;
  jumpChance.value=String(data.bot.jumpChance);
  walkInterval.value=String(data.bot.walkIntervalMs);
  render();
}
document.querySelector("#connect").addEventListener("click",async()=>{
  connectionStatus.textContent="Connecting…";
  try{
    const data=await apiRequest("GET");
    setForm(data);
    connectionStatus.textContent="Connected · revision "+data.revision;
  }catch(error){connectionStatus.textContent="Connection failed: "+error.message}
});
document.querySelector("#disconnect").addEventListener("click",()=>{
  apiToken.value="";
  connectionStatus.textContent="Disconnected; token cleared from this page.";
  saveStatus.textContent="";
});
document.querySelector("#loadRemote").addEventListener("click",async()=>{
  saveStatus.textContent="Loading…";
  try{const data=await apiRequest("GET");setForm(data);saveStatus.textContent="Loaded revision "+data.revision+"."}
  catch(error){saveStatus.textContent="Load failed: "+error.message}
});
document.querySelector("#saveRemote").addEventListener("click",async()=>{
  saveStatus.textContent="";
  try{
    const payload=remotePayload();
    if(!/^[A-Za-z0-9_]{1,16}$/.test(payload.skin.username))throw new Error("Enter a valid Minecraft username.");
    if(payload.skin.enabled&&!/^https:\/\/textures\.minecraft\.net\/texture\/[a-fA-F0-9]+$/.test(payload.skin.textureUrl))throw new Error("Enter a valid textures.minecraft.net texture URL.");
    if(!Number.isFinite(payload.bot.jumpChance)||payload.bot.jumpChance<0||payload.bot.jumpChance>1)throw new Error("Jump chance must be between 0 and 1.");
    if(!Number.isInteger(payload.bot.walkIntervalMs)||payload.bot.walkIntervalMs<100||payload.bot.walkIntervalMs>60000)throw new Error("Movement interval must be 100–60000 ms.");
    const data=await apiRequest("PUT",payload);
    saveStatus.textContent="Saved securely · revision "+data.revision;
  }catch(error){saveStatus.textContent="Save failed: "+error.message}
});
[botName,skinEnabled,skinUrl,skinModel,movementMode,jumpChance,walkInterval].forEach(el=>el.addEventListener("input",render));
document.querySelector("#download").addEventListener("click",()=>{
  const blob=new Blob([yaml()],{type:"text/yaml;charset=utf-8"});
  const url=URL.createObjectURL(blob),a=document.createElement("a");
  a.href=url;a.download="config.yml";a.click();URL.revokeObjectURL(url);
});
document.querySelector("#copy").addEventListener("click",async()=>{
  await navigator.clipboard.writeText(yaml());
  const button=document.querySelector("#copy");button.textContent="Copied!";
  setTimeout(()=>button.textContent="Copy YAML",1400);
});
render();
